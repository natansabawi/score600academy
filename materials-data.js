// Helper to extract Google Drive File ID from various link formats
window.extractGoogleDriveId = function(input) {
  if (!input) return "";
  const trimmed = input.trim();
  
  // Match standard /file/d/ID/ patterns
  const fileDMatch = trimmed.match(/\/file\/d\/([a-zA-Z0-9_-]+)/);
  if (fileDMatch) return fileDMatch[1];

  // Match id=ID or open?id=ID patterns
  const idParamMatch = trimmed.match(/[?&]id=([a-zA-Z0-9_-]+)/);
  if (idParamMatch) return idParamMatch[1];

  // If input is already an ID (alphanumeric string without slashes)
  if (/^[a-zA-Z0-9_-]{15,}$/.test(trimmed)) {
    return trimmed;
  }

  return trimmed;
};

// Helper to construct secure preview link
window.buildGoogleDrivePreviewUrl = function(fileIdOrUrl) {
  const fileId = window.extractGoogleDriveId(fileIdOrUrl);
  if (!fileId) return "";
  return `https://drive.google.com/file/d/${fileId}/preview`;
};

